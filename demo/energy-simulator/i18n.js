// Longest first prevents short labels from replacing parts of a longer sentence.
const pattern = new RegExp(Object.keys(spanish).sort((a,b)=>b.length-a.length).map(key=>key.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('|'),'g');
/** @param {string} text */
export function t(text) {
  if (lang !== 'es') return text;
  return text.replace(pattern, key => /** @type {Record<string,string>} */ (spanish)[key]);
}
/** Translate rendered labels without modifying inputs, JSON evidence or domain values. @param {Node} root */
export function localize(root) {
  if (lang !== 'es') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.parentElement?.closest('script,style,pre')) node.textContent = t(node.textContent || '');
  }
  if (root instanceof Element || root instanceof Document) {
    root.querySelectorAll('[aria-label]').forEach(node => node.setAttribute('aria-label',t(node.getAttribute('aria-label') || '')));
  }
}
